"""Exports: application-level output as Excel (multi-sheet) and CSV. Source workbook is never touched."""
from __future__ import annotations

import io
from pathlib import Path
from typing import List

import pandas as pd

from . import config
from .insights import by_code, product_recommendations, tpv_breakdown

DASHBOARD_COLUMNS = {
    "application_id": "Application ID", "application_status": "Application status", "onboarding_stage": "Onboarding stage",
    "diagnosed_reason": "Diagnosed reason", "code": "Rejection code", "code_source": "Code source",
    "supporting_evidence": "Supporting evidence", "fixability": "Fixability", "recovery_decision": "Recovery decision",
    "decision_state": "Decision state", "standard_fix": "Standard fix", "preferred_language": "Preferred language",
    "channel": "Communication channel", "draft_subject": "Draft subject (email)", "draft_nudge": "Draft nudge",
    "nudge_status": "Nudge status", "nudge_generation": "Nudge generated by", "confidence": "Confidence score",
    "human_review": "Human review", "review_reasons": "Review reasons", "friction_level": "Friction level",
    "friction_indicators": "Friction indicators", "recommended_intervention": "Recommended intervention",
    "priority": "Priority", "priority_score": "Priority score", "priority_rank": "Queue rank",
    "priority_reason": "Priority explanation", "followup_plan": "Follow-up plan", "followup_status": "Follow-up status",
    "expected_monthly_tpv_inr_lakh": "Expected monthly TPV (INR lakh, declared - not actual revenue)",
    "days_since_last_activity": "Days since last activity", "attempts": "Attempts", "support_contacts": "Support contacts",
    "dropout_reason": "Merchant's stated dropout reason (R13 reply)",
    "business_type": "Business type", "industry": "Industry", "city": "City", "whatsapp_opted_in": "WhatsApp opted in",
}


def output_table(res) -> pd.DataFrame:
    cols = [c for c in DASHBOARD_COLUMNS if c in res.df.columns]
    return res.df[cols].rename(columns=DASHBOARD_COLUMNS)


def excel_bytes(res) -> bytes:
    interventions = config.load_rules("product_interventions.json")
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        output_table(res).to_excel(xw, sheet_name="Recovery_Output", index=False)
        q = res.df[res.df["recovery_eligible"]].sort_values("priority_rank")
        q[["priority_rank", "application_id", "expected_monthly_tpv_inr_lakh", "days_since_last_activity",
           "friction_indicators", "priority_score", "priority", "priority_reason", "recommended_intervention"]] \
            .to_excel(xw, sheet_name="Recovery_Queue", index=False)
        res.df[["application_id", "friction_level", "friction_points", "friction_indicators", "pain_point",
                "recommended_intervention"]].to_excel(xw, sheet_name="Friction", index=False)
        fu = []
        for aid, s in res.sequences.items():
            for st in s["steps"]:
                fu.append({"application_id": aid, "step": st["step"], "day": st["day"], "channel": st["channel"],
                           "purpose": st["purpose"], "status": st["status"], "message": st["message"]})
            if not s["steps"]:
                fu.append({"application_id": aid, "step": "-", "status": s["stop_reason"]})
        pd.DataFrame(fu).to_excel(xw, sheet_name="Followups", index=False)
        by_code(res.df).to_excel(xw, sheet_name="Causes_by_code", index=False)
        product_recommendations(res.df, interventions).to_excel(xw, sheet_name="Product_Recommendations", index=False)
        for dim in ("onboarding_stage", "business_type", "industry", "preferred_language"):
            tpv_breakdown(res.df, dim).to_excel(xw, sheet_name=f"TPV_by_{dim}"[:31], index=False)
        summ = {k: v for k, v in res.summary.items() if not isinstance(v, (list, dict))}
        pd.DataFrame([summ]).T.reset_index().rename(columns={"index": "metric", 0: "value"}).to_excel(xw, sheet_name="Summary", index=False)
    return buf.getvalue()


def write_exports(res, out_dir: Path) -> List[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    xlsx = out_dir / "recovery_output.xlsx"
    xlsx.write_bytes(excel_bytes(res))
    csv = out_dir / "recovery_output.csv"
    output_table(res).to_csv(csv, index=False, encoding="utf-8-sig")
    return [xlsx, csv]
